// Бюджет одного теста в браузере.
//
// Karma гоняет тесты через mocha, а у mocha таймаут по умолчанию — 2000 мс, и это не выбор
// проекта, а её собственная константа. Тест Compose в браузере измеряется не своей работой:
// первый в сессии платит инициализацию сцены и шрифтов, а каждый барьер по кадру зависит от
// того, когда браузер этот кадр отдаст. На нагруженном раннере CI две секунды кончаются, и
// падение выглядит как провал проверки — в отчёте видно только "Error", без имени утверждения.
// Так `NavGraphStabilityTest.graphIsBuiltOnce` падал двумя прогонами из трёх на неизменённом
// дереве (youndie/mani#149, 05.09.2026).
//
// 60 секунд — заведомо больше любой честной медленности и всё ещё конечны: тест, который не
// завершится никогда, по-прежнему свалится, просто позже. Число выбрано так, а не подгонкой:
// сам `graphIsBuiltOnce` в браузере стоит около 5 мс, первый тест сессии — около 70 мс.
//
// `client` собирается слиянием: в нём уже лежит `args`, через который Gradle передаёт фильтр
// `--tests`, и присваивание объекта целиком этот фильтр молча выбрасывает.
config.set({
    client: Object.assign({}, config.client, {
        mocha: Object.assign({}, config.client && config.client.mocha, { timeout: 60000 }),
    }),
});
