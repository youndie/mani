package io.github.youndie.mani.feature.health

/**
 * Идёт ли остановка процесса.
 *
 * Порт, а не флаг из библиотеки: остановкой по порядку занимается kore, но kore нужен только
 * нативной сборке — она одна получает SIGTERM от оркестратора. Тянуть его в общую часть значило
 * бы добавить зависимость JVM-сборке, которой она нечего дать.
 *
 * Спрашивает это проба готовности. Смысл вопроса в том, чтобы k8s убрал под из endpoints ДО
 * того, как начнётся слив: под, который уже отказывает, но всё ещё числится готовым, получает
 * новые запросы и отвечает на них 503 — то есть отказ виден клиенту, а не только поду.
 */
fun interface ShuttingDown {
    fun isShuttingDown(): Boolean

    companion object {
        /**
         * Сборка, у которой упорядоченной остановки нет.
         *
         * Это JVM-сборка: она собирается и проверяется, но не разворачивается, и отвечать на
         * этот вопрос ей нечем. Не `TODO()` и не исключение — умолчание обязано быть безопасным,
         * иначе проба готовности падала бы там, где остановки просто не бывает.
         */
        val NEVER: ShuttingDown = ShuttingDown { false }
    }
}
