package io.github.youndie.mani.web

/** Год и `immutable`: браузер не перепроверяет файл вовсе, даже по кнопке «обновить». */
const val CACHE_IMMUTABLE = "public, max-age=31536000, immutable"

/**
 * Хранить можно, использовать — только перепроверив. С ETag перепроверка неизменившегося файла —
 * это `304` без тела; без валидатора тот же заголовок означал бы полную перекачку на каждый заход.
 */
const val CACHE_REVALIDATE = "no-cache"

/** Столько шестнадцатеричных цифр webpack даёт своим именам; короче — не хеш, а обычное имя. */
private const val HASH_LENGTH = 16

/**
 * Навсегда кэшируется только то, чьё **имя** зависит от содержимого.
 *
 * Правило «расширение `.wasm` — значит immutable» выглядит верным и неверно: в бандле лежит
 * `skiko.wasm` с постоянным именем рядом с `6e23e5428398b92da386.wasm`. Пометив первый
 * неизменяемым на год, мы получили бы браузеры, до которых обновление Compose не доезжает
 * вовсе, — и починить это выкатом было бы нельзя, только сменой имени файла.
 *
 * Поэтому проверяется имя, а не расширение: имя из одних шестнадцатеричных цифр webpack даёт
 * ровно тем файлам, которые пересобираются под новым именем при любой правке.
 */
fun String.isContentHashed(): Boolean {
    val name = substringAfterLast('/').substringBeforeLast('.', "")
    return name.length >= HASH_LENGTH && name.all { it in '0'..'9' || it in 'a'..'f' }
}

/**
 * Политика кэширования файла фронтенда по его пути — одна для обеих сборок сервера.
 *
 * Ресурсы Compose (`composeResources/...`) сюда попадают как все: имя у них постоянное, значит
 * `immutable` им нельзя. Срок свежести (`max-age`) им тоже не дан, и не только из осторожности:
 * рядом со шрифтами лежит `values/strings.commonMain.cvr`, а сгенерированный код читает из него
 * строки **по смещениям**. Свежий `mani.js` поверх закэшированного `.cvr` прочитал бы мусор.
 * Перепроверка неизменившегося шрифта стоит `304` в ~300 байт.
 */
fun cacheControlFor(path: String): String = if (path.isContentHashed()) CACHE_IMMUTABLE else CACHE_REVALIDATE
